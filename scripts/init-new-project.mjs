import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const root = resolve(scriptDir, '..');
const migrationsDir = resolve(root, 'supabase', 'migrations');
const outputFile = resolve(root, 'supabase', 'bootstrap.sql');

const preferredOrder = [
  '20240701_budget_management.sql',
  '20250626094643_humble_coast.sql',
  '20240702_add_payment_method_to_transactions.sql',
  '20260619000100_default_categories_for_new_users.sql',
];

const availableFiles = new Set(
  readdirSync(migrationsDir).filter((file) => file.endsWith('.sql'))
);

const migrationFiles = [
  ...preferredOrder.filter((file) => availableFiles.has(file)),
  ...[...availableFiles].filter((file) => !preferredOrder.includes(file)).sort((a, b) => a.localeCompare(b)),
];

if (migrationFiles.length === 0) {
  throw new Error('No Supabase migration files found.');
}

const sections = migrationFiles.map((file) => {
  const filePath = resolve(migrationsDir, file);
  const content = readFileSync(filePath, 'utf8').trimEnd();
  return [
    `-- ============================================================`,
    `-- Migration: ${file}`,
    `-- ============================================================`,
    content,
    '',
  ].join('\n');
});

mkdirSync(resolve(root, 'supabase'), { recursive: true });
writeFileSync(
  outputFile,
  [
    '-- Auto-generated by `npm run init:new-project`.',
    '-- Apply this file to a fresh Supabase project to recreate the current schema and defaults.',
    '',
    ...sections,
  ].join('\n'),
  'utf8'
);

console.log(`Generated ${outputFile}`);
console.log(`Included ${migrationFiles.length} migration file(s):`);
for (const file of migrationFiles) {
  console.log(`- ${file}`);
}
console.log('');
console.log('Next steps for a fresh Supabase project:');
console.log('1. Create a new Supabase project.');
console.log('2. Run this script again after any schema change.');
console.log('3. Apply supabase/bootstrap.sql in the SQL editor, or push the migrations with the Supabase CLI.');
console.log('4. Update VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY in your .env file.');
